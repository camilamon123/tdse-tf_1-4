/* ===================== SPI low-level ===================== */

static HAL_StatusTypeDef spi_tx(ssd1306_t *d, const uint8_t *data, size_t len)
{
  return HAL_SPI_Transmit(d->hspi, (uint8_t*)data, (uint16_t)len, 200);
}

static HAL_StatusTypeDef write_cmd1(ssd1306_t *d, uint8_t c)
{
  cs_low(d);
  dc_cmd(d);
  HAL_StatusTypeDef st = spi_tx(d, &c, 1);
  cs_high(d);
  return st;
}

static HAL_StatusTypeDef write_cmd2(ssd1306_t *d, uint8_t c, uint8_t p)
{
  uint8_t b[2] = { c, p };
  cs_low(d);
  dc_cmd(d);
  HAL_StatusTypeDef st = spi_tx(d, b, 2);
  cs_high(d);
  return st;
}

static HAL_StatusTypeDef write_cmd3(ssd1306_t *d, uint8_t c, uint8_t p1, uint8_t p2)
{
  uint8_t b[3] = { c, p1, p2 };
  cs_low(d);
  dc_cmd(d);
  HAL_StatusTypeDef st = spi_tx(d, b, 3);
  cs_high(d);
  return st;
}

static HAL_StatusTypeDef write_data(ssd1306_t *d, const uint8_t *data, size_t len)
{
  cs_low(d);
  dc_data(d);
  HAL_StatusTypeDef st = spi_tx(d, data, len);
  cs_high(d);
  return st;
}

static void hw_reset(ssd1306_t *d)
{
  /* Reset activo en bajo */
  res_low(d);
  HAL_Delay(10);
  res_high(d);
  HAL_Delay(10);
}

/* ===================== Public API ===================== */

HAL_StatusTypeDef SSD1306_Init(ssd1306_t *d,
                               SPI_HandleTypeDef *hspi,
                               GPIO_TypeDef *cs_port, uint16_t cs_pin,
                               GPIO_TypeDef *dc_port, uint16_t dc_pin,
                               GPIO_TypeDef *res_port, uint16_t res_pin,
                               uint8_t addr7 )
{
  (void)addr7;

  if (!d || !hspi || !cs_port || !dc_port || !res_port) return HAL_ERROR;

  memset(d, 0, sizeof(*d));

  d->hspi     = hspi;
  d->cs_port  = cs_port;  d->cs_pin  = cs_pin;
  d->dc_port  = dc_port;  d->dc_pin  = dc_pin;
  d->res_port = res_port; d->res_pin = res_pin;

  d->width  = (uint8_t)SSD1306_WIDTH;
  d->height = (uint8_t)SSD1306_HEIGHT;
  d->pages  = (uint8_t)SSD1306_PAGES;

  d->x_offset = 0u;
  d->cursor_x = 0u;
  d->cursor_y = 0u;

  /* Estado seguro */
  cs_high(d);
  dc_cmd(d);
  res_high(d);

  hw_reset(d);

  /* Init sequence SSD1306 (clásica) */
  if (write_cmd1(d, 0xAE) != HAL_OK) return HAL_ERROR;                 /* display off */
  if (write_cmd2(d, 0xD5, 0x80) != HAL_OK) return HAL_ERROR;           /* clock div */
  if (write_cmd2(d, 0xA8, (uint8_t)(d->height - 1u)) != HAL_OK) return HAL_ERROR; /* multiplex */
  if (write_cmd2(d, 0xD3, 0x00) != HAL_OK) return HAL_ERROR;           /* display offset */
  if (write_cmd1(d, 0x40) != HAL_OK) return HAL_ERROR;                 /* start line = 0 */

  /* charge pump on (para módulos comunes) */
  if (write_cmd2(d, 0x8D, 0x14) != HAL_OK) return HAL_ERROR;

  /* memory addressing mode: horizontal */
  if (write_cmd2(d, 0x20, 0x00) != HAL_OK) return HAL_ERROR;

  /* remap + scan dir */
  if (write_cmd1(d, 0xA1) != HAL_OK) return HAL_ERROR;                 /* seg remap */
  if (write_cmd1(d, 0xC8) != HAL_OK) return HAL_ERROR;                 /* com scan dec */

  /* COM pins config */
  if (d->height == 64u)
  {
    if (write_cmd2(d, 0xDA, 0x12) != HAL_OK) return HAL_ERROR;
  }
  else
  {
    if (write_cmd2(d, 0xDA, 0x02) != HAL_OK) return HAL_ERROR;
  }

  /* contrast */
  if (write_cmd2(d, 0x81, 0x7F) != HAL_OK) return HAL_ERROR;

  /* precharge + vcom */
  if (write_cmd2(d, 0xD9, 0xF1) != HAL_OK) return HAL_ERROR;
  if (write_cmd2(d, 0xDB, 0x40) != HAL_OK) return HAL_ERROR;

  if (write_cmd1(d, 0xA4) != HAL_OK) return HAL_ERROR;                 /* resume RAM */
  if (write_cmd1(d, 0xA6) != HAL_OK) return HAL_ERROR;                 /* normal display */
  if (write_cmd1(d, 0xAF) != HAL_OK) return HAL_ERROR;                 /* display on */

  SSD1306_Clear(d);
  return SSD1306_Update(d);
}

void SSD1306_Clear(ssd1306_t *d)
{
  if (!d) return;
  memset(d->buf, 0x00, sizeof(d->buf));
  d->cursor_x = 0u;
  d->cursor_y = 0u;
}

void SSD1306_Fill(ssd1306_t *d, uint8_t color)
{
  if (!d) return;
  memset(d->buf, color ? 0xFF : 0x00, sizeof(d->buf));
}

HAL_StatusTypeDef SSD1306_Update(ssd1306_t *d)
{
  if (!d) return HAL_ERROR;

  /* Set column address */
  uint8_t col_start = d->x_offset;
  uint8_t col_end   = (uint8_t)(d->x_offset + d->width - 1u);

  if (write_cmd3(d, 0x21, col_start, col_end) != HAL_OK) return HAL_ERROR;
  if (write_cmd3(d, 0x22, 0x00, (uint8_t)(d->pages - 1u)) != HAL_OK) return HAL_ERROR;

  /* Enviar framebuffer completo */
  return write_data(d, d->buf, (size_t)(d->width * d->pages));
}

/* ===================== Drawing ===================== */

void SSD1306_DrawPixel(ssd1306_t *d, uint8_t x, uint8_t y, uint8_t color)
{
  if (!d) return;
  if (x >= d->width || y >= d->height) return;

  uint16_t index = (uint16_t)x + (uint16_t)(y / 8u) * (uint16_t)d->width;
  uint8_t  mask  = (uint8_t)(1u << (y & 7u));

  if (color) d->buf[index] |= mask;
  else       d->buf[index] &= (uint8_t)~mask;
}

void SSD1306_SetCursor(ssd1306_t *d, uint8_t x, uint8_t y)
{
  if (!d) return;
  d->cursor_x = x;
  d->cursor_y = y;
}

void SSD1306_DrawChar5x7(ssd1306_t *d, char c)
{
  if (!d) return;

  if (c < 32 || c > 126) c = '?';
  const uint8_t *glyph = font5x7[(uint8_t)c - 32u];

  /* Cada char: 5 px ancho + 1 columna de espacio */
  uint8_t x0 = d->cursor_x;
  uint8_t y0 = d->cursor_y;

  /* Dibuja columnas (bits verticales) */
  for (uint8_t col = 0; col < 5u; col++)
  {
    uint8_t bits = glyph[col];
    for (uint8_t row = 0; row < 7u; row++)
    {
      uint8_t on = (bits >> row) & 0x01u;
      SSD1306_DrawPixel(d, (uint8_t)(x0 + col), (uint8_t)(y0 + row), on);
    }
  }

  /* espacio entre chars */
  for (uint8_t row = 0; row < 7u; row++)
  {
    SSD1306_DrawPixel(d, (uint8_t)(x0 + 5u), (uint8_t)(y0 + row), 0u);
  }

  d->cursor_x = (uint8_t)(d->cursor_x + 6u);
}

void SSD1306_DrawString5x7(ssd1306_t *d, const char *s)
{
  if (!d || !s) return;

  while (*s)
  {
    char c = *s++;

    if (c == '\n')
    {
      d->cursor_x = 0u;
      d->cursor_y = (uint8_t)(d->cursor_y + 8u);
      continue;
    }
    if (c == '\r')
      continue;

    /* Wrap simple por ancho */
    if ((uint8_t)(d->cursor_x + 6u) >= d->width)
    {
      d->cursor_x = 0u;
      d->cursor_y = (uint8_t)(d->cursor_y + 8u);
    }

    /* si se fue de alto se cortaaa */
    if ((uint8_t)(d->cursor_y + 7u) >= d->height)
      break;

    SSD1306_DrawChar5x7(d, c);
  }
}
