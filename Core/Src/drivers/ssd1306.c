/* ===================== GPIO helpers ===================== */

static inline void cs_low(ssd1306_t *d)  { HAL_GPIO_WritePin(d->cs_port,  d->cs_pin,  GPIO_PIN_RESET); }
static inline void cs_high(ssd1306_t *d) { HAL_GPIO_WritePin(d->cs_port,  d->cs_pin,  GPIO_PIN_SET); }

static inline void dc_cmd(ssd1306_t *d)  { HAL_GPIO_WritePin(d->dc_port,  d->dc_pin,  GPIO_PIN_RESET); }
static inline void dc_data(ssd1306_t *d) { HAL_GPIO_WritePin(d->dc_port,  d->dc_pin,  GPIO_PIN_SET); }

static inline void res_low(ssd1306_t *d) { HAL_GPIO_WritePin(d->res_port, d->res_pin, GPIO_PIN_RESET); }
static inline void res_high(ssd1306_t *d){ HAL_GPIO_WritePin(d->res_port, d->res_pin, GPIO_PIN_SET); }

