static uint8_t uart2_rx_byte = 0;  // PuTTY (USART2)
static uint8_t uart1_rx_byte = 0;  // HC-05 (USART1)

static volatile uint16_t rx_w = 0, rx_r = 0;
static rx_item_t rxq[RXQ_SZ];

static inline void rxq_push_isr(uint8_t src, uint8_t b)
{
  uint16_t next = (uint16_t)((rx_w + 1U) % RXQ_SZ);
  if (next == rx_r) return; // cola llena -> descartamos
  rxq[rx_w].src = src;
  rxq[rx_w].b   = b;
  rx_w = next;
}

static int rxq_pop(rx_item_t *out)
{
  int ok = 0;
  __disable_irq();
  if (rx_r != rx_w) {
    *out = rxq[rx_r];
    rx_r = (uint16_t)((rx_r + 1U) % RXQ_SZ);
    ok = 1;
  }
  __enable_irq();
  return ok;
}
