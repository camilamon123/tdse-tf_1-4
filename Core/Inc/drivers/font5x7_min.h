static inline const uint8_t* Font5x7_Get(char c)
{
  const uint8_t *q = NULL;

  for (unsigned i = 0; i < sizeof(font5x7_min)/sizeof(font5x7_min[0]); i++)
  {
    if (font5x7_min[i].c == c) return font5x7_min[i].col;
    if (font5x7_min[i].c == '?') q = font5x7_min[i].col;
  }
  return q ? q : font5x7_min[0].col; /* fallback extremo */
}

